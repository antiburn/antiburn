//! The menu-bar / system-tray item.
//!
//! Left click toggles the popover; right click opens a short menu. The menu
//! carries Quit because an agent application has no Dock icon and no
//! application menu — without it there would be no way to exit antiburn.

use tauri::AppHandle;
use tauri::image::Image;
use tauri::menu::{Menu, MenuEvent, MenuItem, PredefinedMenuItem};
use tauri::tray::{MouseButton, MouseButtonState, TrayIcon, TrayIconBuilder, TrayIconEvent};

use crate::{popover, settings};

/// Generated by `apps/desktop/scripts/generate-icons.mjs`; see the icons
/// README for provenance. Embedded rather than read at runtime so a damaged
/// installation cannot leave the app running with no menu-bar presence.
const TRAY_ICON: &[u8] = include_bytes!("../icons/tray.png");

const MENU_SETTINGS: &str = "settings";
const MENU_QUIT: &str = "quit";

/// Builds the menu-bar item and wires up its click and menu handling.
pub fn create(app: &AppHandle) -> tauri::Result<TrayIcon> {
    let menu = build_menu(app)?;

    TrayIconBuilder::with_id("antiburn")
        .icon(Image::from_bytes(TRAY_ICON)?)
        // macOS renders template images tinted for the current menu-bar
        // appearance, including the inverted pressed state.
        .icon_as_template(true)
        .tooltip("antiburn")
        .menu(&menu)
        // The menu belongs to the secondary button; the primary button is the
        // popover toggle.
        .show_menu_on_left_click(false)
        .on_tray_icon_event(on_tray_event)
        .on_menu_event(on_menu_event)
        .build(app)
}

fn build_menu(app: &AppHandle) -> tauri::Result<Menu<tauri::Wry>> {
    let settings_item = MenuItem::with_id(app, MENU_SETTINGS, "Settings…", true, None::<&str>)?;
    let separator = PredefinedMenuItem::separator(app)?;
    let quit_item = MenuItem::with_id(app, MENU_QUIT, "Quit antiburn", true, None::<&str>)?;

    Menu::with_items(app, &[&settings_item, &separator, &quit_item])
}

fn on_tray_event(tray: &TrayIcon, event: TrayIconEvent) {
    // Act on release, not press: pressing and dragging away should not toggle.
    if let TrayIconEvent::Click {
        button: MouseButton::Left,
        button_state: MouseButtonState::Up,
        rect,
        ..
    } = event
    {
        popover::toggle(tray.app_handle(), rect);
    }
}

fn on_menu_event(app: &AppHandle, event: MenuEvent) {
    match event.id().as_ref() {
        MENU_SETTINGS => {
            // No pane in particular: the tray's Settings item is a general
            // entry point, so it leaves the window wherever it was last.
            if let Err(error) = settings::open(app, None) {
                eprintln!("antiburn: could not open settings ({error})");
            }
        }
        MENU_QUIT => {
            // Exit code 0 distinguishes a deliberate quit from the window
            // closes the shell suppresses (see `on_window_event`).
            app.exit(0);
        }
        _ => {}
    }
}
