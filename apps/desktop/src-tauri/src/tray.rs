const RESET_ONBOARDING_LABEL: &str = "Reset Onboarding";
#[cfg(debug_assertions)]
const RANDOM_USAGE_LABEL: &str = "Simulate Random Usage";
#[cfg(debug_assertions)]
const BURN_CHECKS_LABEL: &str = "Simulate Burn Checks";

/// Debug-only state that replaces a report with stable sample findings.
#[cfg(debug_assertions)]
pub struct DebugBurnChecks {
    enabled: Mutex<bool>,
}

#[cfg(debug_assertions)]
impl Default for DebugBurnChecks {
    fn default() -> Self {
        Self {
            enabled: Mutex::new(false),
        }
    }
}

/// The tray menu items whose text follows app state.
///
/// Held as managed state because the menu is built once and the pin item has to
/// be re-labelled later. Two things make that sound: `MenuItem<R>` is an
/// `Arc<MenuItemInner<R>>` that tauri declares `Send + Sync`, and `set_text`
/// marshals through `run_main_thread!`, which runs its closure inline when the
/// caller is already on the main thread — as [`on_menu_event`] is.
pub struct TrayMenu {
    pin: MenuItem<Wry>,
    #[cfg(debug_assertions)]
    random_usage: CheckMenuItem<Wry>,
    #[cfg(debug_assertions)]
    burn_checks: CheckMenuItem<Wry>,
}

struct BuiltMenu {
    menu: Menu<Wry>,
    pin: MenuItem<Wry>,
    #[cfg(debug_assertions)]
    random_usage: CheckMenuItem<Wry>,
    #[cfg(debug_assertions)]
    burn_checks: CheckMenuItem<Wry>,
}

/// The label the pin item carries for a given state — it names the action, not
/// the condition, so a pinned window offers "Unpin Window".
fn pin_label(pinned: bool) -> &'static str {
    if pinned { UNPIN_LABEL } else { PIN_LABEL }
}

/// Builds the menu-bar item and wires up its click and menu handling.
pub fn create(app: &AppHandle) -> tauri::Result<TrayIcon> {
    #[cfg(target_os = "macos")]
    install_app_menu(app)?;

    let menu = build_menu(app)?;
    app.manage(TrayMenu {
        pin: menu.pin,
        #[cfg(debug_assertions)]
        random_usage: menu.random_usage,
        #[cfg(debug_assertions)]
        burn_checks: menu.burn_checks,
    });
    #[cfg(debug_assertions)]
    app.manage(DebugBurnChecks::default());

    let tray = TrayIconBuilder::with_id(TRAY_ID)
        .icon(Image::from_bytes(TRAY_ICON)?)
        // macOS renders template images tinted for the current menu-bar
        // appearance, including the inverted pressed state.
        .icon_as_template(true)
        .tooltip("antiburn")
        .menu(&menu.menu)
        // The menu belongs to the secondary button; the primary button is the
        // popover toggle. Linux ignores this option, because the AppIndicator
        // menu opens on every click.
        .show_menu_on_left_click(false)
        .on_tray_icon_event(on_tray_event)
        .on_menu_event(on_menu_event)
        .build(app)?;

    #[cfg(target_os = "macos")]
    tray.with_inner_tray_icon(|inner| inner.set_highlight_override(Some(false)))?;

    Ok(tray)
}

#[cfg(target_os = "macos")]
fn install_app_menu(app: &AppHandle) -> tauri::Result<()> {
    let menu = Menu::default(app)?;
    let items = menu.items()?;
    let app_menu = items
        .first()
        .and_then(|item| item.as_submenu())
        .ok_or_else(|| anyhow::anyhow!("the default macOS menu has no application submenu"))?;
    let settings_item = MenuItem::with_id(app, MENU_SETTINGS, "Settings...", true, Some("Cmd+,"))?;
    // The tray handler receives application menu events with the same ID.
    app_menu.insert_items(&[&settings_item, &PredefinedMenuItem::separator(app)?], 2)?;
    app.set_menu(menu)?;
    Ok(())
}

/// Register the tray meter after the initial full icon is visible.
pub fn install_usage_meter(app: &AppHandle) {
    app.manage(UsageMeter::default());
}

/// Move the tray meter to the most constrained valid allowance in a snapshot.
///
/// No valid percentage means the ordinary full mark. That is neutral: it does
/// not claim that every allowance is unused.
pub fn sync_usage(
    app: &AppHandle,
    summary: &crate::dto::LiveUsageSummary,
    active: bool,
    launch: bool,
) {
    #[cfg(debug_assertions)]
    if let Some(used) = debug_used_percent(app) {
        set_usage(app, Some(used), true, Some(UPDATE_TRANSITION));
        return;
    }
    let used = active.then(|| usage_used_percent(summary)).flatten();
    let transition = if used.is_some() {
        Some(if launch {
            LAUNCH_TRANSITION
        } else {
            UPDATE_TRANSITION
        })
    } else {
        None
    };
    set_usage(app, used, false, transition);
}

/// Restore the neutral tray mark immediately when usage monitoring is inactive.
pub fn clear_usage(app: &AppHandle) {
    set_usage(app, None, false, None);
}

/// Toggle a debug-only random usage value without changing persisted usage.
#[cfg(debug_assertions)]
fn toggle_random_usage(app: &AppHandle) -> bool {
    let Some(meter) = app.try_state::<UsageMeter>() else {
        return false;
    };
    let used = {
        let mut state = meter
            .state
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        if state.debug_used_percent.is_some() {
            state.debug_used_percent = None;
            None
        } else {
            let used = random_debug_used_percent(random_seed());
            state.debug_used_percent = Some(used);
            Some(used)
        }
    };
    if let Some(used) = used {
        set_usage(app, Some(used), true, Some(UPDATE_TRANSITION));
        return true;
    }

    let active = app
        .try_state::<crate::store::Store>()
        .and_then(|store| store.settings().ok())
        .is_some_and(|settings| settings.live_usage_active());
    let summary = app
        .try_state::<crate::usage_alerts::LiveUsage>()
        .map(|live| live.snapshot())
        .unwrap_or_default();
    sync_usage(app, &summary, active, false);
    false
}

/// Toggle stable sample findings without writing simulated data to the store.
#[cfg(debug_assertions)]
fn toggle_burn_checks(app: &AppHandle) -> bool {
    let Some(state) = app.try_state::<DebugBurnChecks>() else {
        return false;
    };
    let mut enabled = state
        .enabled
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    *enabled = !*enabled;
    *enabled
}

/// Replace the report display with predictable development findings.
#[cfg(debug_assertions)]
pub(crate) fn simulate_burn_checks(app: &AppHandle, report: &mut crate::dto::ChecksReportPayload) {
    let enabled = app.try_state::<DebugBurnChecks>().is_some_and(|state| {
        *state
            .enabled
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
    });
    if !enabled {
        return;
    }
    report.estimated_token_burn_basis_points = Some(125);
    report.evidence_settled = false;
    report.pending_evidence = 12;
    for category in &mut report.categories {
        category.finding = 0;
        category.clean = 8;
        category.unavailable = 0;
        category.estimated_token_burn_basis_points = None;
    }
    if let Some(category) = report.categories.first_mut() {
        category.finding = 3;
        category.clean = 5;
        category.estimated_token_burn_basis_points = Some(125);
    }
}

#[cfg(debug_assertions)]
fn debug_used_percent(app: &AppHandle) -> Option<f64> {
    app.try_state::<UsageMeter>().and_then(|meter| {
        meter
            .state
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner())
            .debug_used_percent
    })
}

#[cfg(debug_assertions)]
fn random_seed() -> u128 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_nanos())
        .unwrap_or_default()
}

#[cfg(debug_assertions)]
fn random_debug_used_percent(seed: u128) -> f64 {
    (seed % 101) as f64
}

fn usage_tooltip(used: Option<f64>, simulated: bool) -> String {
    let Some(used) = used else {
        return "antiburn".to_string();
    };
    let remaining = (100.0 - used).round();
    let suffix = if simulated { " (simulated)" } else { "" };
    format!("antiburn — {remaining:.0}% remaining{suffix}")
}

fn set_usage(app: &AppHandle, used: Option<f64>, simulated: bool, transition: Option<Duration>) {
    let main_thread_app = app.clone();
    if let Err(error) = app.run_on_main_thread(move || {
        if let Some(tray) = main_thread_app.tray_by_id(TRAY_ID)
            && let Err(error) = tray.set_tooltip(Some(usage_tooltip(used, simulated)))
        {
            ::tracing::warn!(event = "tray_usage_tooltip_update_failed", error = %error);
        }
        set_columns(
            &main_thread_app,
            used.map(columns_for_used_percent).unwrap_or(COLUMN_COUNT),
            transition,
        );
    }) {
        ::tracing::warn!(event = "tray_usage_update_schedule_failed", error = %error);
    }
}

fn set_columns(app: &AppHandle, target: usize, transition: Option<Duration>) {
    let Some(meter) = app.try_state::<UsageMeter>() else {
        return;
    };
    let immediate = transition.is_none();
    let (current, generation) = {
        let mut state = meter
            .state
            .lock()
            .unwrap_or_else(|poisoned| poisoned.into_inner());
        state.generation = state.generation.wrapping_add(1);
        let generation = state.generation;
        let current = state.columns;
        if immediate {
            state.columns = target;
        }
        (current, generation)
    };

    let steps = current.abs_diff(target);
    if steps == 0 {
        return;
    }
    let Some(transition) = transition else {
        schedule_columns(app, target, generation);
        return;
    };

    let app = app.clone();
    tauri::async_runtime::spawn(async move {
        let delay = transition / u32::try_from(steps).expect("tray dot count fits in u32");
        for step in 1..=steps {
            tokio::time::sleep(delay).await;
            let Some(meter) = app.try_state::<UsageMeter>() else {
                return;
            };
            let mut state = meter
                .state
                .lock()
                .unwrap_or_else(|poisoned| poisoned.into_inner());
            if state.generation != generation {
                return;
            }
            let columns = if target < current {
                current - step
            } else {
                current + step
            };
            state.columns = columns;
            drop(state);
            schedule_columns(&app, columns, generation);
        }
    });
}

fn schedule_columns(app: &AppHandle, columns: usize, generation: u64) {
    let main_thread_app = app.clone();
    if let Err(error) = app.run_on_main_thread(move || {
        let current = main_thread_app
            .try_state::<UsageMeter>()
            .is_some_and(|meter| {
                let state = meter
                    .state
                    .lock()
                    .unwrap_or_else(|poisoned| poisoned.into_inner());
                frame_is_current(&state, columns, generation)
            });
        if current {
            apply_columns(&main_thread_app, columns);
        }
    }) {
        ::tracing::warn!(event = "tray_usage_icon_schedule_failed", error = %error);
    }
}

fn frame_is_current(state: &UsageMeterState, columns: usize, generation: u64) -> bool {
    state.generation == generation && state.columns == columns
}

fn apply_columns(app: &AppHandle, columns: usize) {
    let Some(tray) = app.tray_by_id(TRAY_ID) else {
        return;
    };
    let image = meter_image(columns);
    if let Err(error) = tray.set_icon_with_as_template(Some(image), true) {
        ::tracing::warn!(event = "tray_usage_icon_update_failed", error = %error);
    }
}

fn meter_image(columns: usize) -> Image<'static> {
    let source = Image::from_bytes(TRAY_ICON).expect("the embedded tray icon is a valid PNG");
    let mut rgba = source.rgba().to_vec();
    let dot_masks = tray_dot_alpha_indices(&rgba, source.width(), source.height());

    let depleted_columns = COLUMN_COUNT.saturating_sub(columns);
    let depleted_dots = DOTS_PER_COLUMN.iter().take(depleted_columns).sum();
    for dot in dot_masks.into_iter().take(depleted_dots) {
        for alpha in dot {
            rgba[alpha] /= DEPLETED_ALPHA_DIVISOR;
        }
    }
    Image::new_owned(rgba, source.width(), source.height())
}

fn tray_dot_alpha_indices(rgba: &[u8], width: u32, height: u32) -> Vec<Vec<usize>> {
    let mut dots = vec![Vec::new(); DOT_COUNT];
    for y in 0..height {
        for x in 0..width {
            let alpha = usize::try_from((y * width + x) * 4 + 3).expect("tray pixel fits usize");
            if rgba[alpha] == 0 {
                continue;
            }
            let dot = DOT_CENTERS
                .iter()
                .enumerate()
                .min_by_key(|(_, (center_x, center_y))| {
                    let dx = i64::from(x) - i64::from(*center_x);
                    let dy = i64::from(y) - i64::from(*center_y);
                    dx * dx + dy * dy
                })
                .expect("the tray has dot centers")
                .0;
            dots[dot].push(alpha);
        }
    }
    debug_assert!(dots.iter().all(|dot| !dot.is_empty()));
    dots
}

fn usage_used_percent(summary: &crate::dto::LiveUsageSummary) -> Option<f64> {
    summary
        .providers
        .iter()
        .filter(|provider| provider_is_displayable(summary, provider))
        .flat_map(visible_windows)
        .filter_map(|window| window.used_percent)
        .filter(|percent| percent.is_finite() && (0.0..=100.0).contains(percent))
        .max_by(f64::total_cmp)
}

fn columns_for_used_percent(used: f64) -> usize {
    ((100.0 - used) * COLUMN_COUNT as f64 / 100.0).round() as usize
}

fn provider_is_displayable(
    summary: &crate::dto::LiveUsageSummary,
    provider: &crate::dto::LiveProviderUsage,
) -> bool {
    let Some(_error) = summary
        .errors
        .iter()
        .find(|error| error.provider == provider.provider)
    else {
        return true;
    };
    let Ok(generated_at) = time::OffsetDateTime::parse(
        &summary.generated_at,
        &time::format_description::well_known::Rfc3339,
    ) else {
        return true;
    };
    let Ok(observed_at) = time::OffsetDateTime::parse(
        &provider.observed_at,
        &time::format_description::well_known::Rfc3339,
    ) else {
        return true;
    };
    generated_at - observed_at <= time::Duration::seconds(LIVE_USAGE_GRACE_SECONDS)
}

fn visible_windows(provider: &crate::dto::LiveProviderUsage) -> Vec<&crate::dto::LiveUsageWindow> {
    let local_antigravity = provider.source_label.starts_with("Read from Antigravity");
    let primary: Vec<_> = provider
        .windows
        .iter()
        .filter(|window| ANTIGRAVITY_PRIMARY_WINDOWS.contains(&window.id.as_str()))
        .collect();
    let candidates = if primary.is_empty() {
        provider.windows.iter().collect()
    } else {
        primary
    };
    candidates
        .into_iter()
        .filter(|window| {
            provider.provider == "google"
                || local_antigravity
                || window.role != "supplemental"
                || window.scope_model.is_none()
                || window.used_percent.unwrap_or(0.0) > 0.0
                || window.has_nonzero_usage_in_current_period
        })
        .collect()
}

/// Returns the menu and a handle to the one item that changes after the build.
///
/// The pin sits above Settings: it acts on the window the reader just had in
/// front of them, where the other two act on the application.
///
/// On Linux the menu is the only route into the popover, so Open goes first as
/// the default action. It needs no separator of its own, because it acts on the
/// same window the pin does.
fn build_menu(app: &AppHandle) -> tauri::Result<BuiltMenu> {
    let pin_item = MenuItem::with_id(
        app,
        MENU_PIN,
        pin_label(popover::is_pinned(app)),
        true,
        None::<&str>,
    )?;
    let settings_item = MenuItem::with_id(app, MENU_SETTINGS, "Settings…", true, None::<&str>)?;
    #[cfg(debug_assertions)]
    let reset_onboarding_item = MenuItem::with_id(
        app,
        MENU_RESET_ONBOARDING,
        RESET_ONBOARDING_LABEL,
        true,
        None::<&str>,
    )?;
    #[cfg(debug_assertions)]
    let random_usage_item = CheckMenuItem::with_id(
        app,
        MENU_RANDOM_USAGE,
        RANDOM_USAGE_LABEL,
        true,
        false,
        None::<&str>,
    )?;
    #[cfg(debug_assertions)]
    let burn_checks_item = CheckMenuItem::with_id(
        app,
        MENU_BURN_CHECKS,
        BURN_CHECKS_LABEL,
        true,
        false,
        None::<&str>,
    )?;
    let separator = PredefinedMenuItem::separator(app)?;
    let quit_item = MenuItem::with_id(app, MENU_QUIT, "Quit antiburn", true, None::<&str>)?;
    let main_item = MenuItem::with_id(app, MENU_MAIN, OPEN_LABEL, true, None::<&str>)?;
    #[cfg(target_os = "linux")]
    let open_popover_item = MenuItem::with_id(
        app,
        MENU_OPEN_POPOVER,
        OPEN_POPOVER_LABEL,
        true,
        None::<&str>,
    )?;

    let items: Vec<&dyn IsMenuItem<Wry>> = vec![
        &main_item,
        #[cfg(target_os = "linux")]
        &open_popover_item,
        &pin_item,
        &settings_item,
        #[cfg(debug_assertions)]
        &reset_onboarding_item,
        #[cfg(debug_assertions)]
        &random_usage_item,
        #[cfg(debug_assertions)]
        &burn_checks_item,
        &separator,
        &quit_item,
    ];
    let menu = Menu::with_items(app, &items)?;
    Ok(BuiltMenu {
        menu,
        pin: pin_item,
        #[cfg(debug_assertions)]
        random_usage: random_usage_item,
        #[cfg(debug_assertions)]
        burn_checks: burn_checks_item,
    })
}

fn on_tray_event(tray: &TrayIcon, event: TrayIconEvent) {
    // Act on release, not press: pressing and dragging away should not toggle.
    if let TrayIconEvent::Click {
        button: MouseButton::Left,
        button_state: MouseButtonState::Up,
        rect,
        ..
    } = event
    {
        // The tray click acknowledges the nudge, even when it closes the popover.
        nudges::dismiss(tray.app_handle());
        popover::toggle(tray.app_handle(), rect);
    }
}

fn on_menu_event(app: &AppHandle, event: MenuEvent) {
    match event.id().as_ref() {
        MENU_MAIN => {
            if let Err(error) =
                crate::open_launch_surface(app, crate::main_window::OpenTrigger::Interaction)
            {
                ::tracing::error!(event = "main_window_open_failed", trigger = "tray", error = %error);
            }
        }
        #[cfg(target_os = "linux")]
        MENU_OPEN_POPOVER => popover::open_from_tray_menu(app),
        MENU_PIN => {
            // The item names the action, so choosing it always means "do the
            // other thing"; the popover is re-shown by `set_pinned`, because
            // opening this menu is what dismissed it.
            popover::set_pinned(app, !popover::is_pinned(app));
            // Read the state back rather than trusting what was asked for, so
            // the label can never claim a pin that did not take.
            let pinned = popover::is_pinned(app);
            if let Some(menu) = app.try_state::<TrayMenu>()
                && let Err(error) = menu.pin.set_text(pin_label(pinned))
            {
                // The pin itself took effect; only the label is stale, and the
                // next state change relabels it.
                ::tracing::warn!(
                    event = "tray_pin_relabel_failed",
                    pinned,
                    error = %error
                );
            }
        }
        MENU_SETTINGS => {
            // The general Settings menu actions do not select a pane. They
            // leave the window wherever it was last.
            if let Err(error) = settings::open(app, None) {
                ::tracing::error!(event = "settings_window_open_failed", error = %error);
            }
        }
        #[cfg(debug_assertions)]
        MENU_RESET_ONBOARDING => {
            if let Err(error) = commands::restart_onboarding(app.clone()) {
                ::tracing::error!(event = "onboarding_restart_failed", trigger = "tray", error);
            }
        }
        #[cfg(debug_assertions)]
        MENU_RANDOM_USAGE => {
            let enabled = toggle_random_usage(app);
            if let Some(menu) = app.try_state::<TrayMenu>()
                && let Err(error) = menu.random_usage.set_checked(enabled)
            {
                ::tracing::warn!(event = "tray_random_usage_relabel_failed", enabled, error = %error);
            }
        }
        #[cfg(debug_assertions)]
        MENU_BURN_CHECKS => {
            let enabled = toggle_burn_checks(app);
            if let Some(menu) = app.try_state::<TrayMenu>()
                && let Err(error) = menu.burn_checks.set_checked(enabled)
            {
                ::tracing::warn!(event = "tray_burn_checks_relabel_failed", enabled, error = %error);
            }
            let _ = app.emit(commands::CHECKS_REPORT_CHANGED_EVENT, ());
        }
        MENU_QUIT => {
            // Exit code 0 distinguishes a deliberate quit from the window
            // closes the shell suppresses (see `on_window_event`).
            crate::main_window::flush_placement(app);
            app.exit(0);
        }
        _ => {}
    }
}

/// Light the menu-bar item, or put it out.
///
/// macOS only draws a *momentary* highlight on a status item: it appears on
/// mouse-down and lets go on mouse-up. So the icon would go flat the instant
/// the popover appeared, and the popover would read as a window floating near
/// the menu bar rather than as this item's surface. Every native menu-bar
/// popover stays lit for as long as it is open; this is how antiburn does the
/// same.
///
/// The state has to stay paired with the popover's visibility, and the pairing
/// lives in [`crate::popover`]: lit in `note_shown`, cleared in `note_hidden`.
/// Every open and every close already runs through that pair, so no caller —
/// including the tray menu's own pin — has to remember the icon separately.
///
/// The vendored tray backend treats this override as the visibility contract.
/// Primary mouse events cannot replace it, and native menu tracking restores
/// its latest value. Remove the patch only when upstream provides both this
/// control and the macOS 27 menu attachment fix recorded in `Cargo.toml`.
///
/// macOS-only; a no-op elsewhere.
#[cfg(target_os = "macos")]
pub fn set_highlight(app: &AppHandle, on: bool) {
    let Some(tray) = app.tray_by_id(TRAY_ID) else {
        return;
    };
    if let Err(error) =
        tray.with_inner_tray_icon(move |inner| inner.set_highlight_override(Some(on)))
    {
        ::tracing::warn!(event = "tray_highlight_update_failed", on, error = %error);
    }
}

#[cfg(not(target_os = "macos"))]
pub fn set_highlight(_app: &AppHandle, _on: bool) {}

